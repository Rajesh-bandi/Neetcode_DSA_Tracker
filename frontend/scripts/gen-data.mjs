// Generates src/data/problems.ts from the tracker exported out of the sheet.
// Source of truth: ../data/tracker-rows.json (sheet tab "Tracker" + its embedded hyperlinks).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(here, '../../data/tracker.csv');
const OUT = resolve(here, '../src/data/problems.ts');

const rows = JSON.parse(readFileSync(resolve(here, '../../data/tracker-rows.json'), 'utf8'));

const DIFFICULTIES = new Set(['Easy', 'Medium', 'Hard']);

const problems = rows.map((r) => {
  const difficulty = r.difficulty;
  if (!DIFFICULTIES.has(difficulty)) {
    throw new Error(`unexpected difficulty ${JSON.stringify(difficulty)} for ${r.title}`);
  }
  if (!r.problemUrl) throw new Error(`no problem url for ${r.title}`);
  if (!r.videoUrl) throw new Error(`no video url for ${r.title}`);
  return {
    week: r.week,
    topic: r.topic,
    lc: r.lc,
    title: r.title,
    difficulty,
    premium: Boolean(r.freeUrl),
    problemUrl: r.problemUrl,
    freeUrl: r.freeUrl || null,
    videoUrl: r.videoUrl,
  };
});

if (problems.length !== 150) {
  throw new Error(`expected 150 problems, got ${problems.length}`);
}

/**
 * Pacing: spread each week's problems over 7 day slots, sized as evenly as
 * possible, and without splitting a topic across days when the whole topic
 * still fits the day being filled.
 */
function assignDays(weekProblems) {
  const n = weekProblems.length;
  const base = Math.floor(n / 7);
  const rem = n % 7;
  const capacity = Array.from({ length: 7 }, (_, i) => base + (i < rem ? 1 : 0));

  const days = [];
  let slot = 0;
  let room = capacity[0];
  while (room === 0 && slot < 6) {
    slot += 1;
    room = capacity[slot];
  }

  const put = (i, j) => {
    for (let k = i; k < j; k += 1) days[k] = slot + 1;
  };

  let i = 0;
  while (i < n) {
    const topic = weekProblems[i].topic;
    let j = i;
    while (j < n && weekProblems[j].topic === topic) j += 1;
    const block = j - i;

    if (block <= room) {
      put(i, j);
      room -= block;
      i = j;
    } else {
      const take = Math.min(room, block);
      put(i, i + take);
      room -= take;
      i += take;
    }

    if (room === 0 && i < n) {
      slot += 1;
      while (capacity[slot] === 0 && slot < 6) slot += 1;
      room = capacity[slot];
    }
  }
  return days;
}

const withDays = [];
for (let week = 1; week <= 12; week += 1) {
  const weekProblems = problems.filter((p) => p.week === week);
  const days = assignDays(weekProblems);
  weekProblems.forEach((p, idx) => withDays.push({ ...p, day: days[idx] }));
}

const weeks = [];
for (let week = 1; week <= 12; week += 1) {
  const weekProblems = withDays.filter((p) => p.week === week);
  const topics = [...new Set(weekProblems.map((p) => p.topic))];
  const lastDay = Math.max(...weekProblems.map((p) => p.day));
  weeks.push({
    week,
    topics,
    count: weekProblems.length,
    days: lastDay,
    easy: weekProblems.filter((p) => p.difficulty === 'Easy').length,
    medium: weekProblems.filter((p) => p.difficulty === 'Medium').length,
    hard: weekProblems.filter((p) => p.difficulty === 'Hard').length,
  });
}

const body = `// GENERATED by scripts/gen-data.mjs from the source spreadsheet - do not edit by hand.
export type Difficulty = 'Easy' | 'Medium' | 'Hard';

export type Problem = {
  /** Stable id, e.g. "w3-56". */
  id: string;
  week: number;
  /** Suggested day slot inside the week (1-7). */
  day: number;
  topic: string;
  lc: number;
  title: string;
  difficulty: Difficulty;
  /** Premium on NeetCode/LeetCode; a free mirror is available. */
  premium: boolean;
  problemUrl: string;
  freeUrl: string | null;
  videoUrl: string;
};

export type WeekMeta = {
  week: number;
  topics: string[];
  count: number;
  days: number;
  easy: number;
  medium: number;
  hard: number;
};

export const PROBLEMS: Problem[] = ${JSON.stringify(
  withDays.map((p) => ({ id: `w${p.week}-${p.lc}`, ...p })),
  null,
  2,
)};

export const WEEKS: WeekMeta[] = ${JSON.stringify(weeks, null, 2)};

export const TOTAL = PROBLEMS.length;
export const DIFFICULTY_TOTALS = {
  Easy: PROBLEMS.filter((p) => p.difficulty === 'Easy').length,
  Medium: PROBLEMS.filter((p) => p.difficulty === 'Medium').length,
  Hard: PROBLEMS.filter((p) => p.difficulty === 'Hard').length,
};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);
console.log(`wrote ${OUT}: ${withDays.length} problems, weeks 1-12`);
console.log('per-week:', weeks.map((w) => w.count).join(', '));
console.log('difficulty:', JSON.stringify({
  Easy: withDays.filter((p) => p.difficulty === 'Easy').length,
  Medium: withDays.filter((p) => p.difficulty === 'Medium').length,
  Hard: withDays.filter((p) => p.difficulty === 'Hard').length,
}));
console.log('day slots per week:', weeks.map((w) => w.days).join(', '));
for (const w of weeks) {
  const sizes = [];
  for (let d = 1; d <= w.days; d += 1) {
    sizes.push(withDays.filter((p) => p.week === w.week && p.day === d).length);
  }
  console.log(`  week ${String(w.week).padStart(2)}: ${w.count} problems -> days ${sizes.join('/')}`);
}
